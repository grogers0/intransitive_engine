use crate::{Player, Piece};

#[derive(Copy, Clone, Eq, PartialEq, Debug)]
pub struct ZobristAccumulator(u64);

fn piece_id(player: Player, piece: Piece) -> usize {
    match (player, piece) {
        (Player::Blue, Piece::Rock) => 0,
        (Player::Blue, Piece::Paper) => 1,
        (Player::Blue, Piece::Scissors) => 2,
        (Player::Red, Piece::Rock) => 3,
        (Player::Red, Piece::Paper) => 4,
        (Player::Red, Piece::Scissors) => 5,
    }
}

impl ZobristAccumulator {
    pub fn new() -> ZobristAccumulator {
        ZobristAccumulator(0)
    }

    pub fn hash_value(&self) -> u64 {
        self.0
    }

    pub fn xor_player(&mut self) {
        self.0 ^= HASHES[NUM_HASHES - 1];
    }

    pub fn xor_piece(&mut self, x: u8, y: u8, player: Player, piece: Piece) {
        let x = x as usize;
        let y = y as usize;
        let id = (9 * y + x) * 6 + piece_id(player, piece);
        debug_assert!(id < NUM_HASHES - 1);
        self.0 ^= HASHES[id];
    }
}

